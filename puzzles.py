def _load_extra() -> list[dict]:
    path = Path(__file__).parent / "puzzles_extra.json"
    if not path.exists():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return [p for p in data if p.get("surface") and p.get("truth")]
    except Exception:
        return []


def all_puzzles() -> list[dict]:
    return PUZZLES + _load_extra()


def pick_unused(used_ids: set[str]) -> dict | None:
    pool = [p for p in all_puzzles() if p.get("id") not in used_ids]
    if not pool:
        used_ids.clear()
        pool = all_puzzles()
    if not pool:
        return None
    return random.choice(pool)
